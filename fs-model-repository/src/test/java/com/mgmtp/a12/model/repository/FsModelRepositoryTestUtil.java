package com.mgmtp.a12.model.repository;

import java.io.IOException;
import java.nio.file.FileVisitResult;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.SimpleFileVisitor;
import java.nio.file.attribute.BasicFileAttributes;
import java.util.List;

class FsModelRepositoryTestUtil {

	static void createInitialRepository(final List<String> models, final String fileExtension, final Path directory)
		throws IOException {
		for (final String modelName : models) {
			final String fileExtensionWithDot = "." + fileExtension;
			final String inFileName = modelName + fileExtensionWithDot;
			final String outFileName = FileNameUtil.getFileNameForModel(modelName) + "." + fileExtension;
			Files.copy(FsModelRepositoryTestUtil.class.getResourceAsStream(inFileName), directory.resolve(outFileName));
		}
	}

	static void emptyDirectory(final Path dir) throws IOException {
		Files.walkFileTree(
			dir, new SimpleFileVisitor<>() {
				@Override
				public FileVisitResult visitFile(final Path file, final BasicFileAttributes attrs) throws IOException {
					Files.delete(file);
					return FileVisitResult.CONTINUE;
				}

				@Override
				public FileVisitResult postVisitDirectory(final Path dir, final IOException exc) throws IOException {
					if (exc == null) {
						Files.delete(dir);
						return FileVisitResult.CONTINUE;
					} else {
						throw exc;
					}
				}
			});
	}

}
