package com.mgmtp.a12.model.utils;

import java.lang.annotation.Documented;
import java.lang.annotation.Retention;
import java.lang.annotation.Target;

import static java.lang.annotation.ElementType.ANNOTATION_TYPE;
import static java.lang.annotation.ElementType.FIELD;
import static java.lang.annotation.ElementType.METHOD;
import static java.lang.annotation.ElementType.PARAMETER;
import static java.lang.annotation.ElementType.TYPE;
import static java.lang.annotation.RetentionPolicy.SOURCE;

/**
 * The caller must not implement the marked target. A specific A12 project provides the implementation. If the A12
 * project adds new methods, this will not be considered as a breaking change.
 *
 * <b>Hint:</b>
 * The marked target does <b>not</b> extend the external API (if there is a corresponding entity in the external API)
 * but is provided independently, because changes to the marked target must always be possible without having to change
 * the API and therefore being breaking.
 */
@Documented
@Target({ TYPE, METHOD, PARAMETER, FIELD, ANNOTATION_TYPE })
@Retention(SOURCE)
public @interface OnlyForUsage {
}
